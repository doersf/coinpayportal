import { notFound } from 'next/navigation';
import { serviceClient } from '@/lib/invoices/catalog';
import { loadPortalInvoice } from '@/lib/contractors/portal';

export const dynamic = 'force-dynamic';

const usd = (n: number | string) => new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(Number(n));
const day = (iso: string | null) => (iso ? new Date(iso.length === 10 ? `${iso}T12:00:00Z` : iso).toLocaleDateString('en-US', { dateStyle: 'long' }) : '');
const kinds: Record<string, string> = { hours: 'Hours', milestone: 'Milestone', expense: 'Expense reimbursement', bonus: 'Bonus', fixed: 'Fixed fee' };

/**
 * The invoice a contractor "issued" for a payment, generated from the lines the
 * pay run paid. Printable; the contractor's records for their own taxes.
 */
export default async function ContractorInvoicePage({ params }: { params: Promise<{ token: string; itemId: string }> }) {
  const { token, itemId } = await params;
  const invoice = await loadPortalInvoice(serviceClient(), token, itemId);
  if (!invoice) notFound();
  const { contractor, business, item, lines } = invoice;
  const c = contractor as typeof contractor & { tax_legal_name?: string | null; tax_business_name?: string | null; tax_address?: string | null };
  const run = item.pay_runs as unknown as { number: number; pay_date: string } | null;

  return (
    <div className="min-h-screen bg-gray-100 py-10 px-4 print:bg-white print:py-0">
      <div className="max-w-3xl mx-auto bg-white text-gray-900 rounded-xl shadow p-10 print:shadow-none">
        <div className="flex justify-between gap-6">
          <div>
            <p className="text-2xl font-bold">Invoice</p>
            <p className="text-gray-500 mt-1">{item.invoice_number}</p>
          </div>
          <div className="text-right text-sm">
            <p className="font-semibold">{c.tax_business_name || c.tax_legal_name || c.name}</p>
            {c.tax_address && <p className="text-gray-600 whitespace-pre-wrap">{c.tax_address}</p>}
            <p className="text-gray-600">{c.email}</p>
          </div>
        </div>

        <div className="grid grid-cols-2 gap-6 mt-8 text-sm">
          <div>
            <p className="text-gray-500 uppercase text-xs tracking-wide">Bill to</p>
            <p className="font-semibold mt-1">{business.name}</p>
          </div>
          <div className="text-right">
            <p><span className="text-gray-500">Issued</span> {day(run?.pay_date ?? item.created_at)}</p>
            <p><span className="text-gray-500">Paid</span> {item.status === 'paid' ? day(item.paid_at) : 'not yet'}</p>
            {run && <p><span className="text-gray-500">Pay run</span> #{run.number}</p>}
          </div>
        </div>

        <table className="w-full mt-8 text-sm">
          <thead>
            <tr className="border-b border-gray-300 text-left text-gray-500">
              <th className="py-2">Date</th><th>Description</th><th className="text-right">Amount</th>
            </tr>
          </thead>
          <tbody>
            {lines.map((l, i) => (
              <tr key={i} className="border-b border-gray-100">
                <td className="py-2 align-top whitespace-nowrap pr-4">{day(l.work_date)}</td>
                <td className="py-2">{kinds[l.kind] ?? l.kind}{l.minutes ? ` (${(l.minutes / 60).toFixed(2)} h)` : ''}: {l.description}</td>
                <td className="py-2 text-right align-top">{usd(l.amount)}</td>
              </tr>
            ))}
          </tbody>
          <tfoot>
            <tr><td colSpan={2} className="pt-4 text-right font-semibold">Total (USD)</td><td className="pt-4 text-right font-semibold">{usd(item.amount)}</td></tr>
          </tfoot>
        </table>

        {item.status === 'paid' && (
          <div className="mt-8 text-xs text-gray-600 space-y-1">
            <p>Paid in {item.payout_currency ?? 'crypto'} to {item.payout_wallet}</p>
            {item.tx_hash && <p className="break-all">Transaction {item.tx_hash}</p>}
          </div>
        )}
        <p className="mt-10 text-xs text-gray-400">Generated by CoinPay from the work approved for this payment.</p>
      </div>
    </div>
  );
}
